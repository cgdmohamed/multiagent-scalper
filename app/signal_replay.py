"""Replay actual Strategy Lab signals against subsequent historical 1m candles.

Cannot regenerate orderbook/CVD strategies from OHLC alone. Existing signals
were generated by the real strategy rules when the feed was available.
This is a conservative execution *approximation*, not an exchange fill.
"""
from bisect import bisect_right
from collections import defaultdict
import math

STRATEGIES=("TREND_SCALP","MOMENTUM_BREAKOUT","ORDERBOOK_PRESSURE_PROXY",
            "EXECUTED_CVD_CONFIRM","VWAP_PULLBACK","TREND_ADX_FILTER",
            "TREND_MACD_RSI_FILTER","TREND_ALL_CONFIRMATIONS")

def _replay_one(signal,bars,starts,fee_bps,slippage_bps,stop_bps,target_bps,hold_minutes):
    try:
        timestamp=int(signal["at_ms"])
        side=1 if signal["direction"]=="LONG" else -1 if signal["direction"]=="SHORT" else 0
    except (ValueError,KeyError,TypeError):
        return None,"INVALID_SIGNAL"
    if not side:return None,"INVALID_SIGNAL"
    # Never enter at a candle open preceding the signal. Deliberately skip
    # the signal's partly formed candle and enter at the next open.
    i=bisect_right(starts,timestamp)
    if i>=len(bars) or starts[i]-timestamp>120000:
        return None,"MISSING_ENTRY_CANDLE"
    if bars[-1][0]<starts[i]+hold_minutes*60000:
        return None,"NOT_ENOUGH_FUTURE_BARS"
    raw_entry=float(bars[i][1])
    spread_bps=max(0,float(signal.get("cost_bps",24))-24)
    # Half estimated signal-time spread per side (no actual entry book).
    impact=(slippage_bps+spread_bps/2)/10000
    entry=raw_entry*(1+side*impact)
    stop=entry*(1-side*stop_bps/10000)
    target=entry*(1+side*target_bps/10000)
    out_price=None;reason=None;exit_i=None
    for j in range(i,min(i+hold_minutes,len(bars))):
        ts,o,h,l,c,v=bars[j]
        if j>i and ts!=bars[j-1][0]+60000:
            return None,"MISSING_CONTIGUOUS_BARS"
        if not all(math.isfinite(x) and x>0 for x in (o,h,l,c)):
            return None,"INVALID_OHLC"
        stop_hit=l<=stop if side==1 else h>=stop
        target_hit=h>=target if side==1 else l<=target
        if stop_hit:
            out_price=min(stop,o) if side==1 else max(stop,o)
            reason="STOP_FIRST"
        elif target_hit:
            out_price=target
            reason="TARGET"
        elif j==i+hold_minutes-1:
            out_price=c
            reason="TIME"
        if reason:
            exit_i=j
            break
    if reason is None:return None,"NOT_ENOUGH_FUTURE_BARS"
    exit_price=out_price*(1-side*impact)
    gross=side*(exit_price/entry-1)*10000
    fees=fee_bps*(1+exit_price/entry)
    net=gross-fees
    return {"strategy":signal["strategy"],"symbol":signal["symbol"],"direction":signal["direction"],
            "signal_at_ms":timestamp,"entry_at_ms":starts[i],"exit_at_ms":bars[exit_i][0],
            "gross_after_spread_slippage_bps":round(gross,3),
            "fees_bps":round(fees,3),"net_bps":round(net,3),
            "outcome":reason,"win":net>0},None

def replay_signals(signals,bars_by_symbol,fee_bps=10,slippage_bps=2,stop_bps=45,target_bps=100,hold_minutes=15):
    if not 1<=hold_minutes<=120 or min(fee_bps,slippage_bps,stop_bps,target_bps)<0:
        raise ValueError("Invalid replay assumptions")
    grouped=defaultdict(list);skipped=defaultdict(int);examples=[]
    indexed={}
    for sym,rows in bars_by_symbol.items():
        ordered=sorted(rows,key=lambda r:r[0])
        indexed[sym]=(ordered,[r[0] for r in ordered])
    for signal in sorted(signals,key=lambda s:s.get("at_ms",0)):
        strategy=signal.get("strategy")
        if strategy not in STRATEGIES:continue
        symbol=signal.get("symbol")
        if symbol not in indexed:
            skipped["NO_HISTORICAL_1M_DATA"]+=1;continue
        bars,starts=indexed[symbol]
        result,reason=_replay_one(signal,bars,starts,fee_bps,slippage_bps,stop_bps,target_bps,hold_minutes)
        if reason:
            skipped[reason]+=1;continue
        grouped[strategy].append(result)
        if len(examples)<20:examples.append(result)
    stats={}
    for strategy in STRATEGIES:
        rows=grouped[strategy]
        if not rows:
            stats[strategy]={"trades":0,"average_net_bps":None,"win_pct":None,"net_pct_on_10pct_allocation":None,"max_closed_drawdown_pct":None}
            continue
        equity=1000.;peak=equity;dd=0
        # To avoid impossible portfolio overlap, report equal-notional cumulative
        # observation equity by strategy, NOT a realized portfolio backtest.
        for row in rows:
            equity=max(0,equity*(1+.10*row["net_bps"]/10000))
            peak=max(peak,equity)
            dd=max(dd,(peak-equity)/peak*100)
        stats[strategy]={"trades":len(rows),"average_net_bps":round(sum(r["net_bps"] for r in rows)/len(rows),3),
            "win_pct":round(100*sum(r["win"] for r in rows)/len(rows),2),
            "net_pct_on_10pct_allocation":round((equity/1000-1)*100,4),
            "max_closed_drawdown_pct":round(dd,4)}
    return {"mode":"RESEARCH_ONLY","strategy_source":"RECORDED_REAL_STRATEGY_LAB_SIGNALS",
            "execution_authority":"NONE","method":"Next 1m candle open after observed signal; stop-first OHLC with modeled fees, spread and slippage; timed exit",
            "assumptions":{"fee_per_side_bps":fee_bps,"slippage_per_side_bps":slippage_bps,
              "stop_bps":stop_bps,"target_bps":target_bps,"max_hold_minutes":hold_minutes,
              "allocation_fraction_for_illustration":.10},
            "results":stats,"skipped":dict(skipped),"example_trades":examples,
            "limitations":"Replays actual observed signals, NOT historical regeneration of signal conditions. Requires historical 1m candles for matching symbols/dates. Signal-time spread is only an estimate; no historical orderbook/trade tape, actual fills, funding, liquidation, or portfolio concurrency. Overlapping signals can overstate effective sample size. No promotion or orders."}
